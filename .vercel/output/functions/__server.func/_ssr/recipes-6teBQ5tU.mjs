function rankForVp(vp) {
	let current = RANKS[0];
	for (const band of RANKS) if (vp >= band.minVp) current = band;
	return current;
}
function nextRank(vp) {
	const current = rankForVp(vp);
	return RANKS[RANKS.findIndex((r) => r.id === current.id) + 1] ?? null;
}
function rankProgress(vp) {
	const current = rankForVp(vp);
	const nxt = nextRank(vp);
	if (!nxt) return 1;
	const span = nxt.minVp - current.minVp;
	return Math.max(0, Math.min(1, (vp - current.minVp) / span));
}
