export function heroRarity(hero: Pick<Hero, "id" | "rarity">): 3 | 4 | 5 {
  if (hero.rarity === 3 || hero.rarity === 4 || hero.rarity === 5) return hero.rarity;
  return RARITY_BELOW_FIVE[hero.id] ?? 5;
}

